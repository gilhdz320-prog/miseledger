"""Builds the 30-second product film from real captures of the app.

No stock footage, no avatars: the screens are the product, the type is the brand,
and the whole thing is regenerated by re-running this script after any UI change.

    python3 film/build.py            # writes film/miseledger.mp4 + film/poster.jpg
"""
import os, subprocess, sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
SHOTS = os.path.expanduser('~/code/teaching-kitchen-os/film/shots')
OUT = os.path.join(HERE, 'miseledger.mp4')
W, H, FPS = 1920, 1080, 30
INK, PAPER, MUTED, ACCENT = (14, 14, 12), (245, 241, 233), (140, 134, 124), (217, 58, 30)
HEL = '/System/Library/Fonts/HelveticaNeue.ttc'

def font(size, index=0):
    try: return ImageFont.truetype(HEL, size, index=index)
    except Exception: return ImageFont.load_default()

F_KICK = font(15); F_TITLE = font(40, 1); F_BIG = font(86, 1); F_SUB = font(20); F_MONO = font(13)

SCENES = [
    dict(kind='title', dur=3.8),
    dict(kind='shot', img='cockpit.png', kicker='THE WEEK', title='The term, laid out once.', dur=5.0),
    dict(kind='shot', img='pantry.png', kicker='THE PANTRY', title='Five pounds is one bag. Not five.', dur=5.0),
    dict(kind='shot', img='temperature.png', kicker='TEMPERATURES', title='Signed, dated, searchable.', dur=5.0),
    dict(kind='shot', img='servsafe.png', kicker='SERVSAFE', title='Every hazard on the map, corrected.', dur=5.0),
    dict(kind='shot', img='counts.png', kicker='COUNTS', title='The shelf, against the sheet.', dur=5.0),
    dict(kind='end', dur=4.5),
]
FADE = 0.55

def bg():
    base = Image.new('RGB', (W, H), INK)
    glow = Image.new('L', (W, H), 0)
    ImageDraw.Draw(glow).ellipse([W*0.10, -H*0.55, W*0.90, H*0.75], fill=46)
    glow = glow.filter(ImageFilter.GaussianBlur(160))
    base.paste(Image.new('RGB', (W, H), (32, 30, 26)), (0, 0), glow)
    return base

BACKGROUND = bg()

def load_card(name):
    im = Image.open(os.path.join(SHOTS, name)).convert('RGB')
    # drop the enterprise banner: the film should start at the product, not the tenant id
    return im.crop((0, 152, im.width, im.height))

def card(img, zoom, card_w=1560, card_h=812):
    """Crops the screen to the card's aspect, applies the slow zoom, rounds the corners."""
    ar = card_w / card_h
    w, h = img.size
    if w / h > ar: nw, nh = int(h * ar), h
    else: nw, nh = w, int(w / ar)
    zw, zh = int(nw / zoom), int(nh / zoom)
    left, top = (w - zw) // 2, 0
    crop = img.crop((left, top, left + zw, top + zh)).resize((card_w, card_h), Image.LANCZOS)
    mask = Image.new('L', (card_w, card_h), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, card_w, card_h], radius=16, fill=255)
    return crop, mask

def paste_card(frame, img, zoom, y=176):
    cw, ch = 1560, 812
    x = (W - cw) // 2
    crop, mask = card(img, zoom)
    shadow = Image.new('RGB', (W, H), (0, 0, 0))
    smask = Image.new('L', (W, H), 0)
    ImageDraw.Draw(smask).rounded_rectangle([x + 8, y + 22, x + cw + 8, y + ch + 22], radius=18, fill=120)
    smask = smask.filter(ImageFilter.GaussianBlur(28))
    frame.paste(shadow, (0, 0), smask)
    frame.paste(crop, (x, y), mask)
    ImageDraw.Draw(frame).rounded_rectangle([x, y, x + cw, y + ch], radius=16, outline=(44, 42, 38), width=2)

def draw_text(frame, kick=None, title=None, sub=None, big=None, kick_y=54, title_y=82, sub_y=None):
    d = ImageDraw.Draw(frame)
    x = (W - 1560) // 2
    if kick:
        d.text((x, kick_y), kick, font=F_KICK, fill=ACCENT)
    if title:
        d.text((x, title_y or kick_y + 34), title, font=F_TITLE, fill=PAPER)
    if sub:
        d.text((x, sub_y or title_y + 66), sub, font=F_SUB, fill=MUTED)
    if big:
        w = d.textlength(big, font=F_BIG)
        d.text(((W - w) / 2, (H - 170) / 2), big, font=F_BIG, fill=PAPER)

def title_frame():
    f = BACKGROUND.copy()
    d = ImageDraw.Draw(f)
    f.paste(Image.new('RGB', (W, H), INK), (0, 0))
    d = ImageDraw.Draw(f)
    mark = 78
    mx, my = (W - mark) // 2, 300
    d.rounded_rectangle([mx, my, mx + mark, my + mark], radius=18, outline=PAPER, width=5)
    for i, wdt in enumerate((34, 46, 24)):
        yy = my + 20 + i * 13
        d.rounded_rectangle([mx + 17, yy, mx + 17 + wdt, yy + 5], radius=3, fill=PAPER)
    d.ellipse([mx + mark - 22, my + mark - 22, mx + mark - 8, my + mark - 8], fill=ACCENT)
    t = 'Mise Ledger'
    d.text(((W - d.textlength(t, font=F_BIG)) / 2, 420), t, font=F_BIG, fill=PAPER)
    s = 'What happened in the kitchen, on the record.'
    d.text(((W - d.textlength(s, font=F_SUB)) / 2, 528), s, font=F_SUB, fill=MUTED)
    return f

def end_frame():
    f = BACKGROUND.copy()
    d = ImageDraw.Draw(f)
    t = 'miseledger.com'
    d.text(((W - d.textlength(t, font=F_BIG)) / 2, 430), t, font=F_BIG, fill=PAPER)
    s = 'Built inside a working teaching kitchen.'
    d.text(((W - d.textlength(s, font=F_SUB)) / 2, 540), s, font=F_SUB, fill=MUTED)
    d.rectangle([W/2 - 28, 620, W/2 + 28, 623], fill=ACCENT)
    return f

CACHE = {}
def scene_frame(i, t):
    sc = SCENES[i]
    p = t / sc['dur']
    if sc['kind'] == 'title': return title_frame()
    if sc['kind'] == 'end': return end_frame()
    key = sc['img']
    if key not in CACHE: CACHE[key] = load_card(key)
    f = BACKGROUND.copy()
    paste_card(f, CACHE[key], 1.015 + 0.055 * p)
    draw_text(f, kick=sc['kicker'], title=sc['title'])
    return f

def mix(a, b, k):
    return Image.blend(a, b, k)

frames = []
cuts = []
acc = 0.0
for sc in SCENES:
    cuts.append(acc); frames.append(sc['dur']); acc += sc['dur']
TOTAL = acc
print(f'{TOTAL:.1f}s, {int(TOTAL*FPS)} frames')

ff = subprocess.Popen([
    os.environ.get('FFMPEG', 'ffmpeg'), '-y', '-loglevel', 'error',
    '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-s', f'{W}x{H}', '-r', str(FPS), '-i', '-',
    '-an', '-c:v', 'libx264', '-preset', 'slow', '-crf', '19', '-pix_fmt', 'yuv420p',
    '-movflags', '+faststart', OUT
], stdin=subprocess.PIPE)

n = int(TOTAL * FPS)
poster_saved = False
for idx in range(n):
    t = idx / FPS
    i = 0
    while i + 1 < len(SCENES) and t >= cuts[i] + frames[i]: i += 1
    local = t - cuts[i]
    img = scene_frame(i, local)
    if i + 1 < len(SCENES) and local > frames[i] - FADE:
        k = (local - (frames[i] - FADE)) / FADE
        img = mix(img, scene_frame(i + 1, max(0, min(FADE, local - frames[i]))), k)
    ff.stdin.write(img.tobytes())
    if not poster_saved and t > 4.6:
        img.save(os.path.join(HERE, 'poster.jpg'), quality=88); poster_saved = True
    if idx % 90 == 0: print('frame', idx, end='\r')

ff.stdin.close(); ff.wait()
print('\nlisto:', OUT, os.path.getsize(OUT) // 1024, 'KB')
